create extension if not exists pgcrypto;

-- --------------------------------------------------------------------------
-- 1. QUEM ADMINISTRA
--    Só usuários listados aqui entram no painel e enxergam pedidos.
-- --------------------------------------------------------------------------
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- --------------------------------------------------------------------------
-- 2. TABELAS
--    Os detalhes de cada registro ficam em "dados" (jsonb), no mesmo formato
--    que o painel já usa. Assim dá para acrescentar campos sem mexer no banco.
-- --------------------------------------------------------------------------
create table if not exists public.config (          -- custos, Pix e dados privados
  id int primary key default 1 check (id = 1),
  dados jsonb not null default '{}'::jsonb,
  atualizado_em timestamptz not null default now()
);

create table if not exists public.site (            -- o que o site público mostra
  id int primary key default 1 check (id = 1),
  dados jsonb not null default '{}'::jsonb,
  atualizado_em timestamptz not null default now()
);

create table if not exists public.filamentos (
  id uuid primary key default gen_random_uuid(),
  dados jsonb not null default '{}'::jsonb,
  criado_em timestamptz not null default now()
);

create table if not exists public.pedidos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  token uuid not null default gen_random_uuid() unique,   -- link secreto do cliente
  status text not null default 'solicitado'
    check (status in ('solicitado','orcamento','comprovante','pago','imprimindo','pronto','enviado','entregue','cancelado','perdido')),
  cliente text,
  dados jsonb not null default '{}'::jsonb,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists pedidos_status_idx on public.pedidos (status);

-- situação "perdido" = orçamento que o cliente não fechou (atualiza também bancos já criados)
alter table public.pedidos drop constraint if exists pedidos_status_check;
alter table public.pedidos add constraint pedidos_status_check
  check (status in ('solicitado','orcamento','comprovante','pago','imprimindo','pronto','enviado','entregue','cancelado','perdido'));
create index if not exists pedidos_criado_idx on public.pedidos (criado_em desc);

create table if not exists public.vitrine (
  id uuid primary key default gen_random_uuid(),
  visivel boolean not null default true,
  destaque boolean not null default false,
  dados jsonb not null default '{}'::jsonb,
  fotos text[] not null default '{}',
  criado_em timestamptz not null default now()
);

insert into public.config (id) values (1) on conflict (id) do nothing;
insert into public.site (id, dados) values (1, '{"nome":"RazenLab"}') on conflict (id) do nothing;

create or replace function public.tocar() returns trigger language plpgsql as $$
begin new.atualizado_em = now(); return new; end $$;

drop trigger if exists pedidos_tocar on public.pedidos;
create trigger pedidos_tocar before update on public.pedidos for each row execute function public.tocar();
drop trigger if exists config_tocar on public.config;
create trigger config_tocar before update on public.config for each row execute function public.tocar();
drop trigger if exists site_tocar on public.site;
create trigger site_tocar before update on public.site for each row execute function public.tocar();

