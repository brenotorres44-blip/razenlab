alter table public.site       enable row level security;
alter table public.filamentos enable row level security;
alter table public.pedidos    enable row level security;
alter table public.vitrine    enable row level security;

drop policy if exists "admin se ve" on public.admins;
create policy "admin se ve" on public.admins for select to authenticated using (user_id = auth.uid());

drop policy if exists "admin tudo" on public.config;
create policy "admin tudo" on public.config for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin tudo" on public.filamentos;
create policy "admin tudo" on public.filamentos for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin tudo" on public.pedidos;
create policy "admin tudo" on public.pedidos for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "todos leem" on public.site;
create policy "todos leem" on public.site for select to anon, authenticated using (true);
drop policy if exists "admin edita" on public.site;
create policy "admin edita" on public.site for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "todos veem visiveis" on public.vitrine;
create policy "todos veem visiveis" on public.vitrine for select to anon, authenticated using (visivel or public.is_admin());
drop policy if exists "admin edita" on public.vitrine;
create policy "admin edita" on public.vitrine for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- HISTÓRICO: cada mudança de situação fica registrada sozinha, com data e hora.
-- É o que permite analisar depois quanto tempo cada orçamento levou para fechar.
create table if not exists public.pedidos_historico (
  id bigint generated always as identity primary key,
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  de text,
  para text not null,
  quem uuid default auth.uid(),
  em timestamptz not null default now()
);
create index if not exists pedidos_historico_pedido_idx on public.pedidos_historico (pedido_id, em);
alter table public.pedidos_historico enable row level security;
drop policy if exists "admin le historico" on public.pedidos_historico;
create policy "admin le historico" on public.pedidos_historico for select to authenticated using (public.is_admin());

create or replace function public.registrar_status() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.pedidos_historico (pedido_id, de, para) values (new.id, null, new.status);
  elsif new.status is distinct from old.status then
    insert into public.pedidos_historico (pedido_id, de, para) values (new.id, old.status, new.status);
  end if;
  return new;
end $$;
drop trigger if exists pedidos_historico_trg on public.pedidos;
create trigger pedidos_historico_trg after insert or update of status on public.pedidos
  for each row execute function public.registrar_status();

-- pedidos que já existiam ganham um primeiro registro, com a data em que foram criados
insert into public.pedidos_historico (pedido_id, de, para, em, quem)
select p.id, null, p.status, p.criado_em, null from public.pedidos p
where not exists (select 1 from public.pedidos_historico h where h.pedido_id = p.id);

grant select on public.site, public.vitrine to anon;
grant select on public.pedidos_historico to authenticated;
grant select, insert, update, delete on public.config, public.site, public.filamentos, public.pedidos, public.vitrine, public.admins to authenticated;

